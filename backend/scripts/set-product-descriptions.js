async function main() {
  if (UPDATES.length === 0) {
    console.log('No updates defined. Uncomment the products you want to update in UPDATES.');
    return;
  }

  const db = await mysql.createConnection({
    host: process.env.DB_HOST,
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME,
  });

  let totalAffected = 0;

  for (const [id, description] of UPDATES) {
    const [result] = await db.query(
      'UPDATE products SET description = ? WHERE id = ?',
      [description, id]
    );
    const status = result.affectedRows > 0 ? 'updated' : 'NOT FOUND';
    console.log(`${id}: ${status}`);
    totalAffected += result.affectedRows;
  }

  console.log(`\nTotal rows updated: ${totalAffected}`);
  await db.end();
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
